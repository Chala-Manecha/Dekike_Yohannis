export const DICTS: Record<Lang, Dict> = { om, am };

export function t(lang: Lang): Dict {
  return DICTS[lang];
}

export function monthName(lang: Lang, month: number) {
  return DICTS[lang].months[month - 1] ?? String(month);
}

export function formatEth(lang: Lang, d: { year: number; month: number; day?: number }) {
  const m = monthName(lang, d.month);
  return d.day ? `${m} ${d.day}, ${d.year}` : `${m} ${d.year}`;
}

export function standingLabel(lang: Lang, info: { kind: "graduate"; graduationYear: number } | { kind: "student"; year: number; gc: boolean }) {
  const s = DICTS[lang].standing;
  if (info.kind === "graduate") return s.graduate(info.graduationYear);
  return info.gc ? s.gc : s.year(info.year);
}
